import fs from "node:fs";
import path from "node:path";

const messages = new Set();
function visit(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (entry.name === "locales" || entry.name === "holidayCatalog.ts")
      continue;
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) visit(file);
    else if (/\.tsx?$/.test(entry.name)) {
      const source = fs.readFileSync(file, "utf8");
      // Source uses Prettier's double-quoted strings. English text is the stable
      // lookup key; template values use named placeholders and stay separate.
      for (const match of source.matchAll(/\bt\(\s*("(?:\\[\s\S]|[^"\\])*")/g))
        messages.add(JSON.parse(match[1]));
      for (const match of source.matchAll(/"(?:\\[\s\S]|[^"\\])*"/g)) {
        const value = JSON.parse(match[0]);
        if (/^[A-Z][A-Za-z’']*\s/.test(value) && !/[{}<>]/.test(value))
          messages.add(value);
      }
    }
  }
}
visit("src");
const catalog = Object.fromEntries(
  [...messages].sort().map((message) => [message, message]),
);
fs.writeFileSync(
  "src/locales/en-AU.ts",
  "// Generated by npm run extract:messages. English is also the fallback catalog.\nexport const ENGLISH_MESSAGES: Readonly<Record<string, string>> = " +
    JSON.stringify(catalog, null, 2) +
    ";\n",
);
console.log(`Extracted ${messages.size} English interface messages.`);
